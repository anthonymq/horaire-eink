#!/usr/bin/env python3
"""Generate a digits-only Adafruit GFX font header (for M5GFX) from a TTF.

Covers '-' to '<' (0x2D-0x3C): "- . / 0-9 : ; <", enough for countdowns,
temperatures and clocks. The GFX fonts bundled with M5GFX stop at 24pt; this
makes bigger, bold digits for the departure countdowns.

    python3 tools/make_digit_font.py Inter-Bold.ttf InterBoldDigits 60 > include/fonts/InterBoldDigits60.h

The size argument is the height in pixels of the digit '0'.
"""
import sys
from PIL import Image, ImageDraw, ImageFont

FIRST, LAST = 0x2D, 0x3C


def ink(font, ch):
    """Rendered glyph and its ink box relative to the pen (baseline origin)."""
    pad = font.size * 2
    img = Image.new("L", (pad * 2, pad * 2), 0)
    ImageDraw.Draw(img).text((pad, pad), ch, font=font, fill=255, anchor="ls")
    img = img.point(lambda v: 255 if v >= 128 else 0)
    box = img.getbbox()
    if box is None:
        return None, (0, 0, 0, 0)
    return img.crop(box), (box[0] - pad, box[1] - pad, box[2] - pad, box[3] - pad)


def load(path, digit_h):
    size = digit_h
    for _ in range(20):
        font = ImageFont.truetype(path, size)
        _, (_, top, _, bottom) = ink(font, "0")
        h = bottom - top
        if h == digit_h:
            return font
        size = max(1, size + (1 if h < digit_h else -1) * max(1, abs(round(size * digit_h / h) - size)))
    return font


def main():
    path, name, digit_h = sys.argv[1], sys.argv[2], int(sys.argv[3])
    font = load(path, digit_h)
    ascent, descent = font.getmetrics()
    bitmap, glyphs = [], []
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        img, (left, top, right, bottom) = ink(font, ch)
        w, h = right - left, bottom - top
        offset = len(bitmap)
        if img is not None:
            bits = [1 if img.getpixel((x, y)) >= 128 else 0 for y in range(h) for x in range(w)]
            bits += [0] * (-len(bits) % 8)
            for i in range(0, len(bits), 8):
                bitmap.append(int("".join(map(str, bits[i:i + 8])), 2))
        glyphs.append((offset, w, h, round(font.getlength(ch)), left, top, ch))

    out = [f"// Generated by tools/make_digit_font.py from {path.split('/')[-1]}"
           f" (digit height {digit_h}px). Do not edit.",
           "#pragma once", "#include <M5GFX.h>", "",
           f"const uint8_t {name}Bitmaps[] PROGMEM = {{"]
    for i in range(0, len(bitmap), 12):
        out.append("  " + ", ".join(f"0x{b:02X}" for b in bitmap[i:i + 12]) + ",")
    out += ["};", "", f"const lgfx::GFXglyph {name}Glyphs[] PROGMEM = {{"]
    for g in glyphs:
        out.append(f"  {{ {g[0]:6d}, {g[1]:3d}, {g[2]:3d}, {g[3]:3d}, {g[4]:4d}, {g[5]:4d} }},  // '{g[6]}'")
    out += ["};", "", f"const lgfx::GFXfont {name} = {{",
            f"  (uint8_t *){name}Bitmaps, (lgfx::GFXglyph *){name}Glyphs,",
            f"  0x{FIRST:02X}, 0x{LAST:02X}, {ascent + descent} }};", ""]
    print("\n".join(out))


if __name__ == "__main__":
    main()
